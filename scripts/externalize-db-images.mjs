// 把数据库里内嵌的 base64 图片（data URI）提取为 static 静态文件，并生成对应的 migration。
// 覆盖三处：card_catalog.image_url、card_catalog.variants、user_cards.selected_image_url。
// 用法：node scripts/externalize-db-images.mjs [sqlite文件路径]
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import sharp from 'sharp';

const root = process.cwd();
const dbPath =
	process.argv[2] ??
	path.join(
		root,
		'.wrangler/state/v3/d1/miniflare-D1DatabaseObject/2c5b4d7bce8f76f122f8e0c6a3eb5005c8110c9505584a8e56e3a0fbddd61307.sqlite'
	);
const catalogImageDir = path.join(root, 'static/images/cards/catalog');
const migrationPath = path.join(root, 'migrations/0015_externalize_db_images.sql');

const MAX_WIDTH = 800;
const WEBP_QUALITY = 82;

function sqlText(value) {
	return `'${String(value).replaceAll("'", "''")}'`;
}

async function dataUriToWebpFile(dataUri, fileName) {
	const match = dataUri.match(/^data:image\/[a-zA-Z+]+;base64,(.+)$/s);
	if (!match) return null;
	const buffer = Buffer.from(match[1], 'base64');
	let pipeline = sharp(buffer);
	const meta = await pipeline.metadata();
	if (meta.width && meta.width > MAX_WIDTH) {
		pipeline = pipeline.resize({ width: MAX_WIDTH, withoutEnlargement: true });
	}
	const output = await pipeline.webp({ quality: WEBP_QUALITY }).toBuffer();
	writeFileSync(path.join(catalogImageDir, fileName), output);
	return { publicPath: `/images/cards/catalog/${fileName}`, bytes: output.length };
}

mkdirSync(catalogImageDir, { recursive: true });
const db = new DatabaseSync(dbPath, { readOnly: true });

const statements = [
	'-- Generated by scripts/externalize-db-images.mjs.',
	'-- 把数据库内嵌的 base64 图片改为 static 文件路径。所有 UPDATE 都带 data: 前缀守卫，可安全重复执行。',
	'',
	'-- 1) 用户卡面若与卡库主图相同，归零让其回退到卡库图片（需在卡库更新前执行）。',
	`UPDATE user_cards SET selected_image_url = NULL
WHERE selected_image_url LIKE 'data:%'
  AND selected_image_url = (SELECT image_url FROM card_catalog c WHERE c.id = user_cards.catalog_id);`,
	'',
	'-- 2) 卡库主图 data URI -> 静态文件。'
];

let totalSaved = 0;

const catalogRows = db
	.prepare("SELECT id, image_url FROM card_catalog WHERE image_url LIKE 'data:%' ORDER BY id")
	.all();
for (const row of catalogRows) {
	const file = await dataUriToWebpFile(row.image_url, `catalog-${row.id}.webp`);
	if (!file) continue;
	totalSaved += row.image_url.length - file.publicPath.length;
	statements.push(
		`UPDATE card_catalog SET image_url = ${sqlText(file.publicPath)} WHERE id = ${row.id} AND image_url LIKE 'data:%';`
	);
	console.log(`catalog #${row.id}: ${(row.image_url.length / 1024).toFixed(0)}KB -> ${file.publicPath} (${(file.bytes / 1024).toFixed(0)}KB)`);
}

statements.push('', '-- 3) 卡库 variants JSON 里的 data URI -> 静态文件。');

const variantRows = db
	.prepare("SELECT id, variants FROM card_catalog WHERE variants LIKE '%data:image%' ORDER BY id")
	.all();
for (const row of variantRows) {
	let variants;
	try {
		variants = JSON.parse(row.variants);
	} catch {
		console.warn(`catalog #${row.id}: variants JSON 解析失败，跳过`);
		continue;
	}
	if (!Array.isArray(variants)) continue;

	let changed = false;
	for (const [index, variant] of variants.entries()) {
		if (typeof variant?.imageUrl !== 'string' || !variant.imageUrl.startsWith('data:')) continue;
		const file = await dataUriToWebpFile(variant.imageUrl, `catalog-${row.id}-v${index}.webp`);
		if (!file) continue;
		totalSaved += variant.imageUrl.length - file.publicPath.length;
		// 用户卡面若选中的是这张变体图，改指到新文件（比对内容而非快照 id，换库执行也成立）。
		statements.push(
			`UPDATE user_cards SET selected_image_url = ${sqlText(file.publicPath)} WHERE selected_image_url = ${sqlText(variant.imageUrl)};`
		);
		variant.imageUrl = file.publicPath;
		changed = true;
		console.log(`catalog #${row.id} variant[${index}] -> ${file.publicPath} (${(file.bytes / 1024).toFixed(0)}KB)`);
	}
	if (changed) {
		statements.push(
			`UPDATE card_catalog SET variants = ${sqlText(JSON.stringify(variants))} WHERE id = ${row.id} AND variants LIKE '%data:image%';`
		);
	}
}

statements.push('', '-- 4) 与卡库无关的孤立用户卡面 data URI -> 静态文件。');

const orphanRows = db
	.prepare(
		`SELECT id, selected_image_url FROM user_cards
		 WHERE selected_image_url LIKE 'data:%'
		   AND selected_image_url != COALESCE((SELECT image_url FROM card_catalog c WHERE c.id = user_cards.catalog_id), '')
		 ORDER BY id`
	)
	.all();
for (const row of orphanRows) {
	const safeId = row.id.replaceAll(/[^a-zA-Z0-9-]/g, '');
	const file = await dataUriToWebpFile(row.selected_image_url, `user-${safeId}.webp`);
	if (!file) continue;
	totalSaved += row.selected_image_url.length - file.publicPath.length;
	statements.push(
		`UPDATE user_cards SET selected_image_url = ${sqlText(file.publicPath)} WHERE id = ${sqlText(row.id)} AND selected_image_url LIKE 'data:%';`
	);
	console.log(`user_card ${row.id} -> ${file.publicPath} (${(file.bytes / 1024).toFixed(0)}KB)`);
}

db.close();
writeFileSync(migrationPath, `${statements.join('\n')}\n`);
console.log(`\nGenerated ${path.relative(root, migrationPath)}`);
console.log(`Estimated DB size reduction: ${(totalSaved / 1024).toFixed(0)}KB`);
